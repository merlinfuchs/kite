#!/usr/bin/env bash
# Generates the nginx config, the systemd units of the service clusters, the
# Kite bot, the web server and the support bot from deploy/config.env. Commit
# the result and apply it with deploy/server.sh.
set -euo pipefail

DEPLOY="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$DEPLOY/config.env"

# split_clients works in steps of 0.01%, util.CluserForKey splits the hash space
# into equal ranges. They only agree when every share is a whole number of steps.
if ((CLUSTER_COUNT < 1 || 10000 % CLUSTER_COUNT != 0)); then
  echo "CLUSTER_COUNT must divide 10000 (1, 2, 4, 5, 8, 10, 16, 20, 25, ...), got $CLUSTER_COUNT." >&2
  exit 1
fi

share=$((10000 / CLUSTER_COUNT))
upstreams=""
shares=""
clusters=""
for ((i = 0; i < CLUSTER_COUNT; i++)); do
  upstreams+="upstream kite_cluster_$i { server 127.0.0.1:$((SERVICE_BASE_PORT + i)); }"$'\n'
  if ((i < CLUSTER_COUNT - 1)); then
    if ((share % 100 == 0)); then
      shares+="        $((share / 100))% \"$i\";"$'\n'
    else
      shares+="$(printf '        %d.%02d%% "%d";' $((share / 100)) $((share % 100)) "$i")"$'\n'
    fi
  else
    shares+="        * \"$i\";"$'\n'
  fi
  clusters+="        \"$i\" kite_cluster_$i;"$'\n'
done

# Sandboxing shared by all units, which run as users without a login, home or
# write access anywhere outside their temp dir. ProtectProc hides other
# processes, like cloudflared with its tunnel token on the command line.
# MemoryDenyWriteExecute is left out, the JavaScript engine compiles to machine
# code with wazero and Node.js has a JIT.
read -r -d '' hardening <<'EOF' || true
NoNewPrivileges=yes
PrivateTmp=yes
PrivateDevices=yes
ProtectSystem=strict
ProtectHome=yes
ProtectProc=invisible
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
ProtectClock=yes
ProtectHostname=yes
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX AF_NETLINK
CapabilityBoundingSet=
SystemCallArchitectures=native
SystemCallFilter=@system-service
EOF

# certbot puts the files that prove we control a domain here, and Let's Encrypt
# fetches them over plain HTTP.
acme_location=$(
  cat <<'EOF'
        # Let's Encrypt checks that we control the domain here.
        location ^~ /.well-known/acme-challenge/ {
                root @ACME_DIR@;
        }
EOF
)

render() {
  local out="$1"
  out="${out//@CLUSTER_COUNT@/$CLUSTER_COUNT}"
  out="${out//@SERVICE_BASE_PORT@/$SERVICE_BASE_PORT}"
  out="${out//@SERVICE_DIR@/$SERVICE_DIR}"
  out="${out//@SERVICE_MEMORY_MAX@/$SERVICE_MEMORY_MAX}"
  out="${out//@SERVICE_GOMEMLIMIT@/$SERVICE_GOMEMLIMIT}"
  out="${out//@WEB_DOMAIN@/$WEB_DOMAIN}"
  out="${out//@DOCS_DOMAIN@/$DOCS_DOMAIN}"
  out="${out//@API_DOMAIN@/$API_DOMAIN}"
  out="${out//@WEB_DIR@/$WEB_DIR}"
  out="${out//@WEB_SERVER_DIR@/$WEB_SERVER_DIR}"
  out="${out//@WEB_PORT@/$WEB_PORT}"
  out="${out//@NODE_BIN@/$NODE_BIN}"
  out="${out//@DOCS_DIR@/$DOCS_DIR}"
  out="${out//@API_MAX_BODY_SIZE@/$API_MAX_BODY_SIZE}"
  out="${out//@OPENPANEL_URL@/$OPENPANEL_URL}"
  out="${out//@ACME_LOCATION@/$acme_location}"
  out="${out//@ACME_DIR@/$ACME_DIR}"
  out="${out//@TLS_DIR@/$TLS_DIR}"
  out="${out//@TLS_CERT_NAME@/$TLS_CERT_NAME}"
  out="${out//@UPSTREAMS@/${upstreams%$'\n'}}"
  out="${out//@SHARES@/${shares%$'\n'}}"
  out="${out//@CLUSTERS@/${clusters%$'\n'}}"
  out="${out//@SUPPORT_DIR@/$SUPPORT_DIR}"
  out="${out//@HARDENING@/$hardening}"
  printf '%s\n' "$out"
}

read -r -d '' nginx_template <<'EOF' || true
# Generated by deploy/generate.sh from deploy/config.env, don't edit.
#
# nginx config for @WEB_DOMAIN@, @DOCS_DOMAIN@ and @API_DOMAIN@, included inside
# the http block. The sites are served over HTTPS, and without TLS on port 80
# of localhost, IPv4 and IPv6, for requests from this machine.

# One certificate for all domains, from Let's Encrypt. deploy/server.sh puts a
# self-signed one there until certbot has issued it, and certbot's deploy hook
# copies each new one there.
ssl_certificate @TLS_DIR@/fullchain.pem;
ssl_certificate_key @TLS_DIR@/privkey.pem;
ssl_session_cache shared:kite_tls:10m;
ssl_session_timeout 1d;

# nginx.conf only compresses HTML.
gzip_types text/plain text/css text/xml text/javascript application/javascript application/json application/xml application/manifest+json image/svg+xml;
gzip_vary on;

# Requests from this machine can pass on the IP of the client they're made for.
# Clients connecting from elsewhere can't set it.
set_real_ip_from 127.0.0.1;
set_real_ip_from ::1;
real_ip_header CF-Connecting-IP;

# Rate limits per API token, or per client IP for requests without one, with
# a stricter one for writes. Clients like Claude and ChatGPT call for all of
# their users from a few IPs, each user with their own token. Only headers
# shaped like a token count as one, so others can't fill the zones with long
# keys. CORS preflights only count towards the general limit, otherwise every
# write counts twice.
map $http_authorization $kite_api_key {
        "~^Bearer (?<kite_token>kite_[A-Za-z0-9_-]{43})$" $kite_token;
        default $binary_remote_addr;
}

map $request_method $kite_api_write_key {
        default $kite_api_key;
        GET     "";
        HEAD    "";
        OPTIONS "";
}

limit_req_zone $kite_api_key zone=kite_api:64m rate=10r/s;
limit_req_zone $kite_api_write_key zone=kite_api_write:64m rate=2r/s;

# nginx can't tell real tokens from made up ones, so every IP has a limit too,
# high enough for all users of a client like Claude together.
limit_req_zone $binary_remote_addr zone=kite_api_ip:16m rate=100r/s;

# Webhooks get their own looser limit. Senders like GitHub and Stripe deliver
# for everyone from a few shared IPs, and the service limits each app itself.
limit_req_zone $binary_remote_addr zone=kite_webhook:16m rate=20r/s;

# OAuth clients like Claude refresh the tokens of all their users from a few
# IPs, without a token in the header, often many at once after an outage.
limit_req_zone $binary_remote_addr zone=kite_oauth_token:16m rate=20r/s;

limit_req_status 429;

# One upstream per service cluster. Requests for an app go to the cluster that
# runs it, split_clients hashes the same way as util.CluserForKey.
@UPSTREAMS@

map $uri $kite_app_id {
        ~^/v1/apps/(?<id>[^/]+)/ $id;
        ~^/v1/webhooks/(?<id>[^/]+)/ $id;
        default "";
}

split_clients "${kite_app_id}" $kite_cluster {
@SHARES@
}

map $kite_cluster $kite_upstream {
        default kite_cluster_0; # requests that aren't for an app
@CLUSTERS@
}

# Users' bundles aren't moderated, so search engines shouldn't list them. The
# page also has a robots meta tag. add_header skips empty values.
map $uri $kite_web_robots {
        ~^/bundles/ noindex;
        default "";
}

# Link preview images set their own Cache-Control. Everything else the web
# server renders is checked on every load.
map $uri $kite_web_cache_control {
        ~^/api/og/ $upstream_http_cache_control;
        default "no-cache";
}

map $http_upgrade $kite_connection_upgrade {
        default upgrade;
        ""      "";
}

# Plain HTTP only answers Let's Encrypt and redirects to HTTPS.
server {
        listen 80 default_server;
        listen [::]:80 default_server;

@ACME_LOCATION@

        location / {
                return 308 https://$host$request_uri;
        }
}

server {
        listen 127.0.0.1:80 default_server;
        listen [::1]:80 default_server;
        listen 443 ssl http2 default_server;
        listen [::]:443 ssl http2 default_server;
        server_name @API_DOMAIN@;

        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $kite_connection_upgrade;
        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Host $host;
        proxy_set_header X-Real-IP $remote_addr;

        client_max_body_size @API_MAX_BODY_SIZE@;
        proxy_connect_timeout 60s;
        proxy_read_timeout 60s;
        proxy_send_timeout 60s;
        send_timeout 60s;

        location / {
                # First, so floods are rejected before they make keys in the
                # other zones.
                limit_req zone=kite_api_ip burst=200 nodelay;
                limit_req zone=kite_api burst=50 delay=10;
                limit_req zone=kite_api_write burst=5;

                proxy_pass http://$kite_upstream;
        }

        location /v1/webhooks/ {
                limit_req zone=kite_webhook burst=100 nodelay;

                proxy_pass http://$kite_upstream;
        }

        location = /v1/oauth/token {
                limit_req zone=kite_oauth_token burst=100 nodelay;

                proxy_pass http://$kite_upstream;
        }

@ACME_LOCATION@
}

server {
        listen 127.0.0.1:80;
        listen [::1]:80;
        listen 443 ssl http2;
        listen [::]:443 ssl http2;
        server_name www.@WEB_DOMAIN@;

@ACME_LOCATION@

        location / {
                return 308 https://@WEB_DOMAIN@$request_uri;
        }
}

server {
        listen 127.0.0.1:80;
        listen [::1]:80;
        listen 443 ssl http2;
        listen [::]:443 ssl http2;
        server_name @WEB_DOMAIN@;

        # public/ of the running build. Everything else is rendered by the
        # Next.js server.
        root @WEB_SERVER_DIR@/public;
        absolute_redirect off;

        # Pages have no trailing slash, so /tools/ redirects to /tools, the
        # canonical URL.
        rewrite ^/(.+)/$ /$1 permanent;

        # Files are checked with the server on every load, so a deploy shows
        # up right away. Locations with their own add_header don't inherit it.
        add_header Cache-Control "no-cache";

        # Served from disk instead of by the server, which only has the files
        # of the current build. Old ones are never deleted, so tabs still open
        # on the previous version can load their chunks.
        location /_next/static/ {
                root @WEB_DIR@;
                add_header Cache-Control "public, max-age=31536000, immutable";
        }

        # Analytics events from the web app, sent here instead of to OpenPanel so
        # blockers don't drop them. OpenPanel takes the client IP from
        # openpanel-client-ip, and doesn't need our cookies.
        location = /ops {
                # Resolved per request, so nginx still starts when the lookup fails.
                resolver 127.0.0.53;
                set $kite_openpanel_url @OPENPANEL_URL@/track;
                proxy_pass $kite_openpanel_url;
                proxy_ssl_server_name on;
                proxy_ssl_verify on;
                proxy_ssl_verify_depth 2;
                proxy_ssl_trusted_certificate /etc/ssl/certs/ca-certificates.crt;
                proxy_set_header openpanel-client-ip $remote_addr;
                proxy_set_header Cookie "";
        }

        location / {
                try_files $uri @web;
        }

        location @web {
                proxy_pass http://127.0.0.1:@WEB_PORT@;
                proxy_set_header Host $host;
                # The MCP server passes the client IP on to the API.
                proxy_set_header X-Real-IP $remote_addr;

                # Pages are checked on every load too. Next.js marks prerendered
                # ones as cacheable for a year by shared caches, which
                # Cloudflare would follow if it ever cached HTML.
                proxy_hide_header Cache-Control;
                add_header Cache-Control $kite_web_cache_control always;
                add_header X-Robots-Tag $kite_web_robots always;
        }

@ACME_LOCATION@
}

server {
        listen 127.0.0.1:80;
        listen [::1]:80;
        listen 443 ssl http2;
        listen [::]:443 ssl http2;
        server_name @DOCS_DOMAIN@;

        root @DOCS_DIR@;
        absolute_redirect off;

        # Docusaurus writes pages as page.html, with trailingSlash: false.
        # page.html comes before page/, since /blog has both.
        rewrite ^/(.+)/$ /$1 permanent;

        # Like the web app's pages, while the files in /assets/ have their
        # hash in their name.
        add_header Cache-Control "no-cache";

        location /assets/ {
                add_header Cache-Control "public, max-age=31536000, immutable";
        }

        location / {
                try_files $uri $uri.html $uri/ =404;
        }

        error_page 404 /404.html;

@ACME_LOCATION@
}
EOF
render "$nginx_template" >"$DEPLOY/nginx.conf"

read -r -d '' tls_hook_template <<'EOF' || true
#!/bin/sh
# Generated by deploy/generate.sh from deploy/config.env, don't edit.
#
# certbot runs this after renewing a certificate, from
# /etc/letsencrypt/renewal-hooks/deploy where deploy/server.sh installs it.
# nginx reads the certificate from @TLS_DIR@.
set -e
[ "$RENEWED_LINEAGE" = /etc/letsencrypt/live/@TLS_CERT_NAME@ ] || exit 0
install -m 600 "$RENEWED_LINEAGE/fullchain.pem" "$RENEWED_LINEAGE/privkey.pem" @TLS_DIR@/
systemctl reload nginx
EOF
render "$tls_hook_template" >"$DEPLOY/certbot-deploy-hook.sh"
chmod +x "$DEPLOY/certbot-deploy-hook.sh"

# systemd expands $ itself, so the port arithmetic for the shell needs $$.
read -r -d '' unit_template <<'EOF' || true
# Generated by deploy/generate.sh from deploy/config.env, don't edit.
#
# Service cluster %i of @CLUSTER_COUNT@, run as kite-service@0 to kite-service@N.
# Reads kite.toml from @SERVICE_DIR@ and applies migrations on every start.
[Unit]
Description=Kite cluster %i
After=network-online.target postgresql.service
Wants=network-online.target
StartLimitIntervalSec=0

[Service]
WorkingDirectory=@SERVICE_DIR@
ExecStartPre=@SERVICE_DIR@/kite-service database migrate postgres up
ExecStart=/bin/sh -c 'exec @SERVICE_DIR@/kite-service server start --cluster_count @CLUSTER_COUNT@ --cluster_index %i --port $$((@SERVICE_BASE_PORT@ + %i))'
Restart=always
RestartSec=5
User=kite
Group=kite
MemoryMax=@SERVICE_MEMORY_MAX@
Environment=GOMEMLIMIT=@SERVICE_GOMEMLIMIT@
# /var/lib/kite, for debug.heap_dump_dir in kite.toml
StateDirectory=kite
@HARDENING@

[Install]
WantedBy=multi-user.target
EOF
render "$unit_template" >"$DEPLOY/kite-service@.service"

# --cluster_count only puts its debug server after the ones of the clusters.
read -r -d '' shared_unit_template <<'EOF' || true
# Generated by deploy/generate.sh from deploy/config.env, don't edit.
#
# The Kite bot, which runs the apps on it, see design/kite-lite.md. Its token
# is shared_bot.token in kite.toml in @SERVICE_DIR@.
[Unit]
Description=Kite bot
After=network-online.target postgresql.service
Wants=network-online.target
StartLimitIntervalSec=0

[Service]
WorkingDirectory=@SERVICE_DIR@
ExecStartPre=@SERVICE_DIR@/kite-service database migrate postgres up
ExecStart=@SERVICE_DIR@/kite-service server start --shared_bot --cluster_count @CLUSTER_COUNT@
Restart=always
RestartSec=5
User=kite
Group=kite
MemoryMax=@SERVICE_MEMORY_MAX@
Environment=GOMEMLIMIT=@SERVICE_GOMEMLIMIT@
# /var/lib/kite, for debug.heap_dump_dir in kite.toml
StateDirectory=kite
@HARDENING@

[Install]
WantedBy=multi-user.target
EOF
render "$shared_unit_template" >"$DEPLOY/kite-shared.service"

# DynamicUser runs the server as a throwaway user that can't write anywhere,
# so it can't change its own files. Next.js then only fails to cache rendered
# pages, which it reads from the build anyway.
read -r -d '' web_unit_template <<'EOF' || true
# Generated by deploy/generate.sh from deploy/config.env, don't edit.
#
# The Next.js server of @WEB_DOMAIN@, deployed to @WEB_SERVER_DIR@ by
# deploy/web.sh. nginx serves /_next/static and public/ itself.
[Unit]
Description=Kite web
StartLimitIntervalSec=0

[Service]
WorkingDirectory=@WEB_SERVER_DIR@
Environment=NODE_ENV=production HOSTNAME=127.0.0.1 PORT=@WEB_PORT@
# The API server of nginx is its default server, so the MCP server reaches it
# without the Cloudflare round trip.
Environment=API_INTERNAL_BASE_URL=http://127.0.0.1
ExecStart=@NODE_BIN@ server.js
# Node exits with 128 + SIGTERM when stopped.
SuccessExitStatus=143
Restart=always
RestartSec=5
DynamicUser=yes
@HARDENING@

[Install]
WantedBy=multi-user.target
EOF
render "$web_unit_template" >"$DEPLOY/kite-web.service"

# Its own user, so the support bot can't read kite.toml.
read -r -d '' support_unit_template <<'EOF' || true
# Generated by deploy/generate.sh from deploy/config.env, don't edit.
#
# The support bot, deployed to @SUPPORT_DIR@ by deploy/support.sh. Reads
# kite-support.toml from there.
[Unit]
Description=Kite support bot
After=network-online.target
Wants=network-online.target
StartLimitIntervalSec=0

[Service]
WorkingDirectory=@SUPPORT_DIR@
ExecStart=@SUPPORT_DIR@/kite-support bot
Restart=always
RestartSec=5
User=kite-support
Group=kite-support
@HARDENING@

[Install]
WantedBy=multi-user.target
EOF
render "$support_unit_template" >"$DEPLOY/kite-support.service"

echo "Generated deploy/nginx.conf, deploy/certbot-deploy-hook.sh, deploy/kite-service@.service, deploy/kite-shared.service, deploy/kite-web.service and deploy/kite-support.service for $CLUSTER_COUNT clusters."
